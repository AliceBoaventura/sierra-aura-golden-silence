'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'game.js'),'utf8');
const runtime={};vm.createContext(runtime);
vm.runInContext(fs.readFileSync(path.join(root,'runtime.js'),'utf8'),runtime);
const start=source.indexOf('function syncTouchScanner(){');
const end=source.indexOf("$('touchScan').onclick",start);
assert(start>=0&&end>start,'the existing scanner button has a sync helper');
const classes=new Set(),attrs={};
const button={classList:{toggle:(name,on)=>on?classes.add(name):classes.delete(name)},setAttribute:(name,value)=>attrs[name]=value};
const ui={scanToggle:false,state:{mode:'playing',chapter:1,scan:false},$:id=>id==='touchScan'?button:null};vm.createContext(ui);
vm.runInContext(source.slice(start,end),ui);
vm.runInContext('syncTouchScanner()',ui);
assert.equal(attrs['aria-pressed'],'false');
assert.equal(attrs['aria-label'],'Ativar scanner');
ui.scanToggle=true;ui.state.scan=true;vm.runInContext('syncTouchScanner()',ui);
assert(classes.has('active'));
assert.equal(attrs['aria-pressed'],'true');
assert.equal(attrs['aria-label'],'Desativar scanner');
// Reproduce a low-energy held touch scanner and the real depletion branch.
const s={mode:'playing',energy:.5,scan:false,scanLock:false};
runtime.NeoRuntime.scan(s,true,.05,16,12);
assert.equal(s.scannerState,'depleted');
const block=source.match(/if\(scanToggle&&state\.scannerState==='depleted'\)\{\s*scanToggle=false;syncTouchScanner\(\);\s*\}/);
assert(block,'depleted touch scanners are automatically released in the game loop');
ui.state=s;vm.runInContext(block[0],ui);
assert.equal(ui.scanToggle,false);
assert.equal(attrs['aria-pressed'],'false');
assert(!classes.has('active'));
runtime.NeoRuntime.scan(s,false,.2,16,12);
assert.equal(s.scanLock,false,'release clears scanner lock');
assert(s.energy>0,'energy recharges after release');
runtime.NeoRuntime.scan(s,true,.02,16,12);
assert.equal(s.scannerState,'active','scanner can be reactivated after recharge');
const lifecycle=fs.readFileSync(path.join(root,'lifecycle.js'),'utf8');
assert(lifecycle.includes('syncTouchScanner();'),'pause and chapter resets synchronize the button');
const prelude=fs.readFileSync(path.join(root,'prelude.js'),'utf8');
assert(prelude.includes('syncTouchScanner();'),'first chapter transitions synchronize the button');
console.log('PASS P44: scanner auto-release on depletion, recharge/rearm, accessible pressed state, pause and chapter reset synchronization');
